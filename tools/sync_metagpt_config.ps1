#requires -Version 5.1
<#
.SYNOPSIS
  Generate the MetaGPT home config (~/.metagpt/config2.yaml) WITHOUT putting an API key on disk.

.DESCRIPTION
  MetaGPT's Config loader only accepts a file (it looks at
  <metagpt install>/config/config2.yaml and then $HOME/.metagpt/config2.yaml -- never the
  repo-root config2.yaml).  That used to mean the live key had to be pasted into the home
  directory.

  It no longer does.  knowledge_agents/baselines/run_metagpt.py overrides api_key / base_url /
  model in-process from SLC_LLM_API_KEY / SLC_LLM_BASE_URL / SLC_LLM_MODEL, so the home file
  only has to satisfy the loader's schema.  This script therefore writes it with a placeholder
  key and the non-secret fields taken from the environment.

  If an existing home config contains a literal key, this script strips it (that is the point).

.PARAMETER WhatIf
  -WhatIf shows what would be written; the key column is never echoed.

.EXAMPLE
  . tools\slc_mars_env.ps1
  .\tools\sync_metagpt_config.ps1          # or -WhatIf first
#>
[CmdletBinding(SupportsShouldProcess = $true)]
param()

$ErrorActionPreference = 'Stop'

$dir  = Join-Path $HOME '.metagpt'
$path = Join-Path $dir 'config2.yaml'

$model = if ($env:SLC_LLM_MODEL)    { $env:SLC_LLM_MODEL }    else { 'REPLACE_OR_COME_FROM_ENV' }
$base  = if ($env:SLC_LLM_BASE_URL) { $env:SLC_LLM_BASE_URL } else { 'REPLACE_OR_COME_FROM_ENV' }

$content = @(
    '# Generated by SCL-Mars/tools/sync_metagpt_config.ps1 -- NO credential lives in this file.'
    '# The live key is injected in-process by knowledge_agents/baselines/run_metagpt.py from'
    '# SLC_LLM_API_KEY (see SCL-Mars/secrets.example.ps1). If you run MetaGPT outside that'
    '# pipeline, export SLC_LLM_* yourself or replace api_key below -- and rotate any key that'
    '# previously sat in a tracked file.'
    'llm:'
    '  api_type: openai'
    "  base_url: $base"
    '  api_key: COME_FROM_SLC_LLM_API_KEY_ENV'
    "  model: $model"
    ''
) -join "`r`n"

if (-not (Test-Path $dir)) {
    if ($PSCmdlet.ShouldProcess($dir, 'create directory')) {
        New-Item -ItemType Directory -Force -Path $dir | Out-Null
    }
}

# Report (never echo) whether the current home file holds a secret.
$status = 'absent'
if (Test-Path $path) {
    $cur = Get-Content $path -Raw -Encoding UTF8
    if ($cur -match 'api_key:\s*(?!\s*$)[^\s#]') {
        $hasValue = ($cur -split "`n" | Where-Object { $_ -match '^\s*api_key:' } |
                     ForEach-Object { (($_ -split ':', 2)[1]).Trim() }) -ne ''
        $looksPlaceholder = $cur -match 'api_key:\s*COME_FROM_SLC_LLM_API_KEY_ENV'
        if ($hasValue -and -not $looksPlaceholder) { $status = 'contains a literal key -> will be stripped' }
        else { $status = 'already placeholder-only' }
    }
}

if ($PSCmdlet.ShouldProcess($path, "write ($status)")) {
    Set-Content -LiteralPath $path -Value $content -Encoding ASCII
    Write-Host "wrote $path  [$status]"
    Write-Host 'model/base_url from env; api_key left as a placeholder on purpose.'
}
