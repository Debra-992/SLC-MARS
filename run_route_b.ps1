# SLC dual-agent launcher (Route B)
# Usage:
#   .\run_route_b.ps1                          # run the fixed demo (compute/knowledge)
#   .\run_route_b.ps1 -Mode question           # random single question, both agents
#   .\run_route_b.ps1 -Mode question -Seed 42  # reproducible random pick
#   .\run_route_b.ps1 -Mode question -Qid <qid># explicit question
# Requires:
#   .venv\              Python 3.11 + metagpt + mcp client
#   outputs\mcp-venv\   Python 3.11 + requirements-tools
#   $SLC_ROOT points to the extracted SLC_fresh handoff bundle

param(
    [string]$Mode = "demo",          # demo | question | answer | eval | baseline | compare | calib | prewarm
    [int]$Seed = -1,
    [string]$Qid = "",
    [int]$Eval = 0,
    [string]$Buckets = "pairwise,membership",
    [string]$DecisionMode = "auto",  # heuristic | llm | auto (auto: the heuristic where evidence is direct, cross-cancer analogy where it is not)
    [string]$Dataset = "clean",      # clean (the science-validity filtered subset) | full (the raw 647)
    [string]$Cancers = ""            # prewarm only: comma-separated cancer list; empty = every cancer in the dataset
)

$ErrorActionPreference = "Stop"
$workspace = $PSScriptRoot

# Ensure UTF-8 output so CJK log lines don't render as mojibake in the console.
try { chcp 65001 | Out-Null } catch {}

# ---- 0. Credentials + machine-local paths: never stored in this file ----------------
# SLC tools read ONLY os.environ; do NOT write .env or config2.yaml.
# Resolution order: pre-set env vars win, otherwise `secrets.local.ps1` at the repo root
# is dot-sourced (untracked; copy secrets.example.ps1 to create it).  That file carries
# SLC_LLM_* / NEO4J_* / MONGO_* and the machine-local $env:SLC_ROOT below.
. "$workspace\tools\load_secrets.ps1"
$slcSecretsSource = Import-SlcSecrets -Root $workspace   # banner is printed; the returned
# source name is captured so it does not leak into the launcher's output stream.
# $env:NEO4J_DATABASE = "neo4j"     # optional; community default is "neo4j"

# ---- 1. Root of your extracted SLC_fresh handoff bundle -----------------------------
if (-not $env:SLC_ROOT) {
    $env:SLC_ROOT = "D:\PATH\TO\SLC_fresh"   # placeholder: set the real path in secrets.local.ps1
}
if (-not (Test-Path $env:SLC_ROOT)) {
    Write-Warning "SLC_ROOT does not exist: $env:SLC_ROOT -- local tool caches will be unavailable"
}
# ------------------------------------------------------------------------------------

# Cache / worker roots
$env:SLC_KMTIMER_ROOT     = "$env:SLC_ROOT\outputs\tool-cache\KMTIMER"
$env:SLC_TOOLS_CACHE_ROOT = "$workspace\outputs\slc-tools-cache"

# Interpreter used by RealMcpBackend to spawn each MCP stdio server
$env:SLC_MCP_PYTHON       = "$workspace\outputs\mcp-venv\Scripts\python.exe"

# Per-tool hard subprocess deadline (seconds)
$env:SLC_MCP_TOOL_TIMEOUT = "45"

# Offline mode: cache-only, never open browser or download TCGA
$env:SLC_TOOLS_OFFLINE    = "0"
# DESeq2 reads local GDCdata when assembled (BRCA/COAD ship ready). For other cancers the counts
# must be pulled from GDC once. We enable live download ONLY in prewarm mode (fetch/assemble once,
# cached into GDCdata + DE cache); graded eval/compare runs keep downloads OFF => deterministic, fast,
# and data-less cancers honestly return download_required instead of stalling the batch.
$env:SLC_MCP_ALLOW_DOWNLOADS = if ($Mode -eq "prewarm") { "1" } else { "0" }
Write-Host "[route B] allow DE downloads = $env:SLC_MCP_ALLOW_DOWNLOADS (mode=$Mode)"
# Keep browser network OFF (we use TIMER/KM from cache only)
$env:SLC_MCP_ALLOW_BROWSER_NETWORK = "0"
# Cap samples per group (default 10) -- smaller = faster smoke test
$env:SLC_TCGA_SAMPLES_PER_GROUP = "6"
# Give the DE tool more headroom than the 45s default (GDC download can be slow)
$env:SLC_MCP_R_TIMEOUT = "900"

# qid whitelist for project_knowledge. Default: the full 647-question public set
# generated by tools\gen_public_inputs.py (any random qid resolves to Neo4j KG).
# Fall back to the 2-case handoff bundle if the generated file is missing.
$generatedInputs = "$workspace\outputs\mcp-public-inputs-all647.json"
if (Test-Path $generatedInputs) {
    $env:SLC_MCP_PUBLIC_INPUTS = $generatedInputs
} else {
    Write-Warning "missing $generatedInputs (run: python tools\gen_public_inputs.py); using shipped 2-case bundle"
    $env:SLC_MCP_PUBLIC_INPUTS = "$env:SLC_ROOT\outputs\tools-20261016T132011Z-d6262c\mcp-public-inputs.json"
}

# ==== Credentials were resolved in section 0 above ====

# ==== DESeq2  (R + TCGA counts) ====
$env:R_HOME      = "C:\Program Files\R\R-4.6.1"
$env:R_LIBS_USER = "$workspace\outputs\R-libs"
# GDCdata raw counts already exist under the tools cache root; make the data root explicit.
$env:SLC_GDCDATA_ROOT = "$workspace\outputs\slc-tools-cache\GDCdata"
# Workspace DE timeout must NOT cut off a real DESeq2 run; align to the R-side budget (SLC_MCP_R_TIMEOUT).
$env:SLC_DE_TIMEOUT   = "900"
# Enable the per-cancer DE disk cache (first cancer pays once, later questions reuse instantly).
$env:SLC_DE_CACHE     = "1"
# DESeq2 already tests all ~509 SLC genes; return a wide top_n so more candidate genes carry a log2FC signal.
$env:SLC_DE_TOPN      = "400"
# prepend R binaries to PATH (x64 first so stats.dll etc. resolve for rpy2/TCGAbiolinks)
$env:Path = "$env:R_HOME\bin\x64;$env:R_HOME\bin;$env:Path"
# rpy2 on Windows reads R's Sys.getenv() into a CSV without an encoding, so a working directory
# whose path contains non-ASCII characters GBK-decode-fails. PYTHONUTF8=1
# forces Python subprocess defaults to UTF-8, which matches what R writes.
$env:PYTHONUTF8 = "1"
# GitPython is imported lazily by MetaGPT (metagpt.actions -> debug_error -> git_repository).
# If git isn't momentarily resolvable in a detached shell, its default refresh() RAISES at import
# and aborts the whole run. We never use git functionality here, so make the import non-fatal.
$env:GIT_PYTHON_REFRESH = "quiet"
# Decision-agent kernel: heuristic (env-free, deterministic) | llm | auto
$env:SLC_DECISION_MODE = $DecisionMode
# Dataset: clean (science-valid subset) | full (raw 647)
$env:SLC_DATASET = $Dataset
# ==== Live TIMER / KM  (Chrome + Driver + on-network) ====
# $env:SLC_TOOLS_OFFLINE          = "0"
# $env:SLC_MCP_ALLOW_BROWSER_NETWORK = "1"
# $env:SLC_ALLOW_DRIVER_DOWNLOAD  = "1"
# $env:CHROME_BINARY              = "C:\Program Files\Google\Chrome\Application\chrome.exe"
# $env:CHROMEDRIVER_PATH          = "C:\tools\chromedriver.exe"

Write-Host "[route B] SLC_ROOT         = $env:SLC_ROOT"
Write-Host "[route B] MCP python       = $env:SLC_MCP_PYTHON"
Write-Host "[route B] tools cache root = $env:SLC_TOOLS_CACHE_ROOT"
Write-Host "[route B] offline          = $env:SLC_TOOLS_OFFLINE"
Write-Host "[route B] public inputs    = $env:SLC_MCP_PUBLIC_INPUTS"

# Metagpt writes INFO/WARNING to stderr; Windows PowerShell would treat those as
# terminating errors under ErrorActionPreference=Stop. Loosen for the run itself.
$ErrorActionPreference = "Continue"
if ($Mode -eq "question") {
    $pyArgs = @("-m", "knowledge_agents.run_single_question")
    if ($Qid) { $pyArgs += @("--qid", $Qid) } elseif ($Seed -ge 0) { $pyArgs += @("--seed", "$Seed") }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} elseif ($Mode -eq "answer") {
    # End-to-end: Kira -> Cael -> Vega, prints each agent's intermediate + final result and the answer
    $pyArgs = @("-m", "knowledge_agents.answer_pipeline", "--buckets", $Buckets)
    if ($Qid) { $pyArgs += @("--qid", $Qid) } elseif ($Seed -ge 0) { $pyArgs += @("--seed", "$Seed") }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} elseif ($Mode -eq "eval") {
    # Batch scoring vs ground_truth over N sampled pairwise/membership questions
    $pyArgs = @("-m", "knowledge_agents.answer_pipeline", "--eval", "$Eval", "--buckets", $Buckets)
    if ($Seed -ge 0) { $pyArgs += @("--seed", "$Seed") }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} elseif ($Mode -eq "baseline") {
    # Native MetaGPT (pure-LLM) baseline on the identical sample; no tools/retrieval/CRISPR
    $pyArgs = @("-m", "knowledge_agents.baseline_metagpt", "--buckets", $Buckets)
    if ($Eval -gt 0) { $pyArgs += @("--eval", "$Eval") }
    if ($Qid) { $pyArgs += @("--qid", $Qid) } elseif ($Seed -ge 0) { $pyArgs += @("--seed", "$Seed") }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} elseif ($Mode -eq "compare") {
    # Fair side-by-side: run pipeline AND native baseline on the SAME clean sample; report coverage/accuracy
    $n = if ($Eval -gt 0) { $Eval } else { 40 }
    $pyArgs = @("-m", "knowledge_agents.compare_eval", "--n", "$n", "--buckets", $Buckets)
    if ($Seed -ge 0) { $pyArgs += @("--seed", "$Seed") }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} elseif ($Mode -eq "calib") {
    # Heuristic-only LARGE calibration pool for conformal abstention (no LLM, tools only).
    $n = if ($Eval -gt 0) { $Eval } else { 250 }
    $pyArgs = @("-m", "knowledge_agents.calib_dump", "--n", "$n", "--buckets", $Buckets)
    if ($Seed -ge 0) { $pyArgs += @("--seed", "$Seed") }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} elseif ($Mode -eq "prewarm") {
    # Warm the DESeq2 cache BEFORE graded runs. Downloads are ON here (see switch above): each cancer's
    # TCGA counts are fetched/assembled from GDC once, then DESeq2 runs and the result is disk-cached.
    # A fresh download+DE is slow, so give DE far more headroom than the graded-run default.
    $env:SLC_DE_TIMEOUT = "1800"
    $pyArgs = @("-m", "knowledge_agents.prewarm_de")
    if ($Cancers) { $pyArgs += @("--cancers", $Cancers) }
    & "$workspace\.venv\Scripts\python.exe" @pyArgs
} else {
    & "$workspace\.venv\Scripts\python.exe" -m knowledge_agents.demo
}
exit $LASTEXITCODE
